export const DICTIONARIES: Record<Language, Dict> = { fr, en, es };

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

/** Interpolates `{name}` placeholders. Missing keys fall back to fr, then the key itself. */
export function translate(dict: Dict, key: string, vars?: Record<string, string | number>): string {
  const template = dict[key] ?? fr[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match
  );
}

/** French translator — default for services called outside React (tests, pure code). */
export const frTranslate: Translate = (key, vars) => translate(fr, key, vars);

/** Browser locale → app language. Matches the language prefix; defaults to French. */
export function detectLanguage(languages: readonly string[] = navigator.languages ?? [navigator.language]): Language {
  for (const lang of languages) {
    const code = lang.toLowerCase();
    if (code.startsWith('fr')) return 'fr';
    if (code.startsWith('en')) return 'en';
    if (code.startsWith('es')) return 'es';
  }
  return 'fr';
}

/** BCP-47 locale for the app language (used by Intl date/number formatting). */
export function localeOf(lang: Language): string {
  switch (lang) {
    case 'fr': return 'fr-FR';
    case 'en': return 'en-US';
    case 'es': return 'es-ES';
  }
}

